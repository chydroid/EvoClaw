/**
 * Canvas Manager — Agent-editable HTML canvas system.
 *
 * Inspired by OpenClaw A2UI. Allows the AI agent to create, edit, and
 * serve dynamic HTML pages as visual outputs. The agent can use the
 * `canvas_create` and `canvas_update` tools to generate dashboards,
 * charts, reports, interactive widgets, and more.
 *
 * Canvas files are served at `/__evoclaw__/canvas/<name>` and support
 * full HTML/CSS/JS including inline scripts, external CDN resources,
 * and EvoClaw API proxy for live data.
 */

import * as fs from "fs";
import * as path from "path";
import * as crypto from "crypto";
import { atomicWriteFileSync } from "./atomic-write";

export interface CanvasConfig {
  /** Directory to store canvas files (default: "data/canvas") */
  storagePath?: string;
  /** Maximum canvas file size in bytes (default: 5MB) */
  maxFileSize?: number;
  /** Maximum number of canvas files (default: 100) */
  maxFiles?: number;
  /** Whether to enable the canvas API endpoints */
  enabled?: boolean;
  /** Allowed CDN origins for script/style resources */
  allowedCDNs?: string[];
}

export interface CanvasFile {
  /** Unique canvas identifier (slug) */
  id: string;
  /** Display title */
  title: string;
  /** HTML content */
  html: string;
  /** Created timestamp */
  createdAt: string;
  /** Last modified timestamp */
  updatedAt: string;
  /** Creator (agent or user) */
  createdBy: "agent" | "user";
  /** Optional tags for organization */
  tags?: string[];
  /** Optional description */
  description?: string;
  /** Whether this canvas is publicly accessible (no auth) */
  public?: boolean;
}

export interface CanvasListResult {
  canvases: Array<{
    id: string;
    title: string;
    description?: string;
    tags?: string[];
    createdAt: string;
    updatedAt: string;
    createdBy: string;
    public: boolean;
    size: number;
  }>;
  total: number;
  storageUsed: number;
  maxFiles: number;
}

