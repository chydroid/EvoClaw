/**
 * 「工作尚未完成」的自我陈述标记（auto-continuation 与 turn-finalizer 共用）
 *
 * v28 压测实证（Task 1 / Task 4）：模型在任务中途产出了一份**完整的进度报告**——
 *   - 「还没做：README、CLI、report.json」
 *   - 「下一步：修正 test_multipart.py 的 body 构造」
 *   - 「我先把剩下的全部跑完再给你最终汇报」
 * 然后结束本轮。旧检测器有两个互补盲区：
 *   - auto-continuation 只认「接下来我将 / 我马上」这类**未来时承诺**，
 *     不认「尚未执行 / 还没做 / 下一步：动词」这类**未完成状态自述** → 不续跑；
 *   - turn-finalizer 只认「尚未完成 / 尚未验证」，于是给一份明确写着
 *     「还在进行中」的回复追加「✅ 已完成」状态块 → 自相矛盾。
 *
 * 两处共用同一份标记，避免再次出现「一个检测器认得、另一个认不得」。
 * 只匹配**工作项**动词（执行/运行/生成…），不匹配「尚未发现异常」等结论性表述。
 */

/** 工作项动作动词（「尚未 X」「还没 X」中的 X） */
const WORK_VERBS =
  "执行|运行|测试|验证|生成|产出|编写|保存|写入|落盘|交付|汇报|完成|实施|修改|创建";

/** 计划式收尾的动词（「下一步：X」中的 X） */
const PLAN_VERBS =
  "修正|修复|运行|执行|生成|测试|验证|重跑|补齐|补全|完成|继续|编写|创建|更新|调整|对齐|跑通|落盘|写入|产出|交付";

export const UNFINISHED_WORK_PATTERNS: readonly RegExp[] = [
  // 「尚未执行 / 尚未向主人汇报 / 还未运行」——(?:向…)? 容纳「尚未向用户汇报」
  new RegExp(`(?:还|尚)未\\s*(?:向[^。\\n]{0,12}?)?\\s*(?:${WORK_VERBS})`),
  // 「还没做 / 还没跑 / 还没写 / 还没开始」
  new RegExp(`还没\\s*(?:做|跑|改|写|开始|${WORK_VERBS})`),
  // 「还没到最后一步 / 还在进行中」
  /(?:还|尚)没\s*到(?:最后一步|最终)|还在进行中|仍在进行/,
  // 「下一步：修正 …」——冒号后必须是动作词，排除「下一步建议：…」这类给用户的建议
  new RegExp(`(?:下一步|接下来|后续)\\s*[:：]\\s*(?:${PLAN_VERBS})`),
  // 「我先把剩下的全部跑完再给你最终汇报」
  /先把[^。\n]{0,30}?(?:跑完|做完|写完|改完|修完|跑通|完成|补全)[^。\n]{0,20}?(?:再|然后|之后)/,
] as const;

/** 文本是否包含「尚未完成」的自我陈述标记 */
export function hasUnfinishedWorkMarker(text: string | null | undefined): boolean {
  if (!text) return false;
  return UNFINISHED_WORK_PATTERNS.some((re) => re.test(text));
}
